// npm run setup
// Creates .env from .env.example if needed, and generates ADMIN_TOKEN if missing.
// Never prints the token.
import { readFileSync, writeFileSync, existsSync, copyFileSync } from "node:fs";
import { join } from "node:path";
import { randomBytes } from "node:crypto";
import { execFileSync } from "node:child_process";
import { ROOT, ENV_PATH, readEnv } from "./lib.mjs";

// Turn on the pre-commit secret guard (scripts/git-hooks/pre-commit) for this clone.
try {
  execFileSync("git", ["config", "core.hooksPath", "scripts/git-hooks"], { cwd: ROOT, stdio: "ignore" });
  console.log("Secret guard enabled: commits containing .env files or keys will be refused.");
} catch {
  console.log("Note: could not enable the git secret guard (is this a git repository?).");
}

if (!existsSync(ENV_PATH)) {
  copyFileSync(join(ROOT, ".env.example"), ENV_PATH);
  console.log("Created .env from .env.example.");
}

const env = readEnv();
const token = env.ADMIN_TOKEN;
if (token && token.length >= 32 && !/REPLACE|generated/i.test(token)) {
  console.log("ADMIN_TOKEN already set in .env. Nothing to do.");
} else {
  const fresh = randomBytes(32).toString("base64url"); // 256 bits
  let text = readFileSync(ENV_PATH, "utf8");
  if (/^\s*ADMIN_TOKEN\s*=.*$/m.test(text)) {
    text = text.replace(/^\s*ADMIN_TOKEN\s*=.*$/m, `ADMIN_TOKEN=${fresh}`);
  } else {
    text = text.replace(/\s*$/, "\n") + `\n# Admin password for the npm scripts. Generated by \`npm run setup\`.\nADMIN_TOKEN=${fresh}\n`;
  }
  writeFileSync(ENV_PATH, text);
  console.log("Generated a new ADMIN_TOKEN in .env (value not shown).");
  console.log("If the server is running, restart it so it picks up the change.");
}
